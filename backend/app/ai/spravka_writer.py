"""ИИ-структурирование текста прокурорской справки в стиле эталона (сем-быт.docx).

Поток:
1. Собираем обезличенные факты/статистику (вызывающий код передаёт уже готовые данные).
2. Токенизируем ПДн (на случай, если в фактах остались ФИО/ИИН/ЕРДР).
3. Шлём в активный LLM-провайдер (Gemini/Ollama) с эталонным стилем.
4. Детокенизируем ответ — реальные ФИО/номера возвращаются локально.
5. Фолбэк: если LLM недоступна — детерминированный шаблонный текст.
"""
from pathlib import Path

from app.ai import llm
from app.ai.guard import detokenize, tokenize_pii

_STYLE_PATH = Path(__file__).parent / "templates" / "spravka_style.txt"

SYSTEM_PROMPT = (
    "Ты — помощник прокурора, готовящий аналитическую справку службы по защите общественных "
    "интересов. Пиши официально-деловым языком в стиле прокурорской справки. Используй ТОЛЬКО "
    "переданные факты и цифры, ничего не выдумывай. Не признавай лиц виновными. Сохраняй "
    "плейсхолдеры вида [ЛИЦО_1], [ЕРДР_1] без изменений. Опирайся на нормы: ст.73, ст.461 КоАП, "
    "ст.107-109 УК, Закон РК «О профилактике правонарушений» №245-VIII, Приказ ГП РК №32."
)

SECTION_TITLES = {
    "police": "По линии органов внутренних дел (полиции)",
    "mio": "По линии местных исполнительных органов (МИО)",
    "proceedings": "Нарушения законности при административном производстве",
    "intro": "Вводная часть",
    "conclusion": "Выводы и меры прокурорского реагирования",
    "health": "По линии органов здравоохранения (ДСБ)",
}


def _style_guide() -> str:
    try:
        return _STYLE_PATH.read_text(encoding="utf-8")
    except Exception:
        return ""


def write_section(scope: str, facts: str, *, temperature: float = 0.3) -> tuple[str, bool]:
    """Возвращает (текст_раздела, использован_ли_LLM).

    `scope` — police|mio|intro|conclusion; `facts` — подготовленные факты/статистика.
    """
    title = SECTION_TITLES.get(scope, scope)
    external = llm.provider() == "gemini"

    sent_facts, pii_map = (tokenize_pii(facts) if external else (facts, {}))
    prompt = (
        f"{_style_guide()}\n\n"
        f"Напиши раздел справки «{title}» (3-6 абзацев) на основе фактов ниже. "
        f"Соблюдай структуру: проблема -> статистика -> примеры -> вывод о формальном подходе -> последствия.\n\n"
        f"ФАКТЫ И СТАТИСТИКА:\n{sent_facts}\n"
    )
    answer = llm.generate(prompt, system=SYSTEM_PROMPT, temperature=temperature)
    if answer and external and pii_map:
        answer = detokenize(answer, pii_map)
    if answer:
        return answer.strip(), True
    return _fallback_section(title, facts), False


def _fallback_section(title: str, facts: str) -> str:
    """Детерминированный текст раздела, если LLM недоступна."""
    return (
        f"{title}.\n\n"
        "Анализ профилактической работы выявил риски формального подхода к исполнению "
        "возложенных обязанностей. Ниже приведены фактические данные и примеры, требующие "
        "мер прокурорского реагирования в соответствии с Приказом ГП РК №32.\n\n"
        f"{facts}\n\n"
        "Изложенное свидетельствует о необходимости устранения нарушений законности, "
        "усиления индивидуальной профилактической работы и контроля за лицами, состоящими "
        "на профилактическом учёте."
    )
