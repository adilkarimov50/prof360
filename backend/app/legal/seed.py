def seed_legal(db: Session) -> int:
    """Идемпотентно создаёт акты и нормы, вычисляет эмбеддинги. Возвращает число норм."""
    count = 0
    pending: list[LegalNorm] = []
    texts: list[str] = []
    for act_data in ACTS:
        norms = act_data.pop("norms")
        existing = db.query(LegalAct).filter(LegalAct.number == act_data["number"]).first()
        if existing:
            act = existing
        else:
            act = LegalAct(**act_data)
            db.add(act)
            db.flush()
        for nd in norms:
            already = (
                db.query(LegalNorm)
                .filter(LegalNorm.act_id == act.id, LegalNorm.article == nd["article"])
                .first()
            )
            if already:
                continue
            norm = LegalNorm(
                act_id=act.id, status="действует",
                edition_start=act.adopt_date, source_url=act.source_url, **nd,
            )
            db.add(norm)
            pending.append(norm)
            texts.append(f"{act.title} {nd['article']} {nd.get('title','')} {nd['text_ru']} {nd.get('keywords','')}")
            count += 1

    if pending:
        vectors = embed_passages(texts)
        for norm, vec in zip(pending, vectors):
            norm.embedding = vec
    db.commit()
    return count


def _norm_embedding_text(norm: LegalNorm) -> str:
    act_title = norm.act.title if norm.act else ""
    return (
        f"{act_title} {norm.article or ''} {norm.title or ''} "
        f"{norm.text_ru or ''} {norm.keywords or ''}"
    ).strip()


def reembed_legal(db: Session) -> int:
    """Пересчитывает эмбеддинги ВСЕХ норм текущей моделью (после смены движка эмбеддингов)."""
    norms = db.query(LegalNorm).all()
    if not norms:
        return 0
    vectors = embed_passages([_norm_embedding_text(n) for n in norms])
    for norm, vec in zip(norms, vectors):
        norm.embedding = vec
    db.commit()
    return len(norms)
