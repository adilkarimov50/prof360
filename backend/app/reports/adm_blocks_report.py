def _fmt(n: int) -> str:
    return f"{n:,}".replace(",", " ")


def _num(x: float) -> str:
    return f"{x}".replace(".", ",")


def _plural(n: int, one: str, few: str, many: str) -> str:
    if n % 10 == 1 and n % 100 != 11:
        return one
    if n % 10 in (2, 3, 4) and n % 100 not in (12, 13, 14):
        return few
    return many


def _table(doc: Document, headers: tuple[str, ...], rows: list[tuple[str, ...]]) -> None:
    table = doc.add_table(rows=1, cols=len(headers))
    for i, h in enumerate(headers):
        cell = table.rows[0].cells[i]
        cell.text = h
        for run in cell.paragraphs[0].runs:
            run.bold = True
    for r in rows:
        cells = table.add_row().cells
        for i, v in enumerate(r):
            cells[i].text = str(v)


def _bullets(doc: Document, items: tuple[str, ...]) -> None:
    for txt in items:
        doc.add_paragraph(txt, style="List Bullet")


def _dynamics_line(stats: dict) -> str:
    return "; ".join(f"{MONTH_RU.get(k, k)} — {v}" for k, v in stats["by_month"].items())


def _measures_line(stats: dict) -> str:
    if not stats.get("measures"):
        return "меры взыскания не зафиксированы"
    return "; ".join(f"{m['name']} — {m['count']}" for m in stats["measures"])


def _enf(a: dict, base: str) -> dict:
    """Данные о полноте взыскания по конкретной статье."""
    for e in a["enforcement_person"] + a["enforcement_road"]:
        if e["article"] == f"ст.{base}":
            return e
    return {"total": 0, "warning": 0, "no_measure": 0, "real_penalty": 0,
            "real_pct": 0.0, "terminated": 0}


